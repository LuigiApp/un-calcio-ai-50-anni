create table if not exists public.rsvp (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 3 and 100),
  attending boolean not null,
  guests smallint not null default 0 check (guests between 0 and 20),
  notes text check (notes is null or char_length(notes) <= 500),
  created_at timestamptz not null default now(),
  constraint attendance_guests_consistency check (
    (attending = true and guests >= 1) or (attending = false and guests = 0)
  )
);

alter table public.rsvp enable row level security;

-- Chiunque abbia l'invito può inviare una risposta, ma non leggere i dati.
drop policy if exists "public can submit rsvp" on public.rsvp;
create policy "public can submit rsvp"
on public.rsvp for insert
to anon, authenticated
with check (
  char_length(trim(name)) between 3 and 100
  and guests between 0 and 20
  and (notes is null or char_length(notes) <= 500)
  and ((attending = true and guests >= 1) or (attending = false and guests = 0))
);

-- Solo utenti autenticati marcati admin nei metadati possono leggere.
drop policy if exists "admins can read rsvp" on public.rsvp;
create policy "admins can read rsvp"
on public.rsvp for select
to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

